player_states = {}

# ---------------------- ФУНКЦИИ ------------------------

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    keyboard = [[InlineKeyboardButton("Присоединиться к игре", callback_data="join")]]
    await update.message.reply_text(
        "💞 Добро пожаловать в love-игру для пары!\n\n"
        "Нажмите кнопку ниже, чтобы присоединиться ❤️",
        reply_markup=InlineKeyboardMarkup(keyboard)
    )

async def join_game(update: Update, context: ContextTypes.DEFAULT_TYPE):
    global players
    query = update.callback_query
    user_id = query.from_user.id

    if user_id in players:
        await query.answer("Вы уже участвуете!")
        return

    if len(players) < 2:
        players.append(user_id)
        player_states[user_id] = {"level": 1, "q_index": 0}
        await query.answer(f"Вы присоединились ({len(players)}/2)")

    if len(players) == 2:
        await query.message.reply_text("✨ Оба игрока на месте! Игра начинается.")
        await ask_question(context, players[0])

async def ask_question(context, user_id):
    state = player_states[user_id]
    level = state["level"]
    q_index = state["q_index"]

    if q_index >= len(questions[level]):
        await context.bot.send_message(user_id, "Все вопросы уровня пройдены!")
        return

    text = f"❓ *Вопрос:* {questions[level][q_index]}"
    keyboard = [
        [InlineKeyboardButton("Следующий вопрос", callback_data="next")],
        [
            InlineKeyboardButton("Шаг ближе 💗", callback_data="closer"),
            InlineKeyboardButton("Шаг теплее 🔥", callback_data="warmer")
        ],
        [InlineKeyboardButton("Закончить игру", callback_data="stop")]
    ]

    await context.bot.send_message(
        chat_id=user_id,
        text=text,
        parse_mode="Markdown",
        reply_markup=InlineKeyboardMarkup(keyboard)
    )

async def button(update: Update, context: ContextTypes.DEFAULT_TYPE):
    global current_player_index
    query = update.callback_query
    user_id = query.from_user.id

    if query.data == "next":
        player_states[user_id]["q_index"] += 1
        current_player_index = 1 - current_player_index
        next_player = players[current_player_index]
        await ask_question(context, next_player)

    elif query.data in ["closer", "warmer"]:
        await query.answer("💞 Эмоции записаны!")

    elif query.data == "stop":
        await query.message.reply_text("Игра завершена 💗")

# ---------------------- ЗАПУСК ------------------------

app = ApplicationBuilder().token("YOUR_TOKEN_HERE").build()

app.add_handler(CommandHandler("start", start))
app.add_handler(CallbackQueryHandler(join_game, pattern="^join$"))
app.add_handler(CallbackQueryHandler(button, pattern="^(next|closer|warmer|stop)$"))

app.run_polling()
